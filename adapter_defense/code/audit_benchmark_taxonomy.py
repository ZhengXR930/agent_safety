#!/usr/bin/env python3
"""Audit benchmark taxonomy labels in the unified manifest."""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from build_benchmark_manifest import PROJECT_ROOT, ROOT, validate


DEFAULT_MANIFEST = PROJECT_ROOT / "experiment-stage" / "adaptive_attack_eval" / "benchmark_manifest.jsonl"
DEFAULT_OUT_DIR = PROJECT_ROOT / "experiment-stage" / "adaptive_attack_eval"


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows = []
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def compact_label_row(row: dict[str, Any]) -> dict[str, Any]:
    labels = row["taxonomy_labels"]
    text = row.get("attacked_input") or row.get("clean_input") or ""
    return {
        "case_id": row["case_id"],
        "benchmark": row["benchmark"],
        "suite": row["suite"],
        "source_path": row["source_path"],
        "surface": row["surface"],
        "primary_attack_category": row["primary_attack_category"],
        "labels": {
            "clean": labels["clean"],
            "value": labels["value"],
            "authority": labels["authority"],
            "policy": labels["policy"],
            "rationale": labels["rationale"],
        },
        "review_status": labels.get("review_status", "missing"),
        "review_reasons": labels.get("review_reasons", []),
        "target": row.get("target", {}),
        "raw_ref": row.get("raw_ref", {}),
        "text_preview": text[:500],
    }


def markdown_table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return lines


def render_report(rows: list[dict[str, Any]], summary: dict[str, Any]) -> str:
    benchmarks = sorted(summary["by_benchmark"].keys())
    source_audit = summary["source_count_audit"]
    primary = summary["by_benchmark_primary_attack_category"]
    label_yes = summary["by_benchmark_label_yes"]
    review_status = summary["by_benchmark_review_status"]

    lines: list[str] = [
        "# Benchmark Taxonomy Audit",
        "",
        "Generated by `python adapter_defense/code/audit_benchmark_taxonomy.py` after `python adapter_defense/code/build_benchmark_manifest.py`.",
        "",
        "Definitions:",
        "",
        "- `clean`: authorized benign task/action.",
        "- `value`: untrusted or unsafe data controls sensitive action arguments or sink payloads.",
        "- `authority`: unauthorized source or insufficient authorization controls the agent's decision to act.",
        "- `policy`: trusted user intent itself requests disallowed harm.",
        "",
        "Each row carries a four-field tuple in `taxonomy_labels`: `{clean,value,authority,policy,rationale}`. `primary_attack_category` is the single denominator bucket used for aggregate tables; the tuple is multi-label.",
        "",
        "## Official Source Counts",
        "",
    ]

    source_rows = []
    for benchmark in benchmarks:
        audit = source_audit.get(benchmark, {})
        components = "<br>".join(f"{name}={count}" for name, count in audit.get("components", {}).items())
        source_rows.append(
            [
                benchmark,
                components,
                audit.get("expected_total", 0),
                audit.get("manifest_total", 0),
                "yes" if audit.get("expected_total", 0) == audit.get("manifest_total", 0) else "no",
            ]
        )
    lines.extend(markdown_table(["Benchmark", "Official/local components", "Expected", "Manifest", "Count OK"], source_rows))

    lines.extend(["", "## Primary Denominator Split", ""])
    primary_rows = []
    for benchmark in benchmarks:
        total = summary["by_benchmark"][benchmark]
        p = primary.get(benchmark, {})
        clean_or_other = total - p.get("authority", 0) - p.get("value", 0) - p.get("policy", 0)
        primary_rows.append(
            [
                benchmark,
                total,
                p.get("authority", 0),
                p.get("value", 0),
                p.get("policy", 0),
                clean_or_other,
                "yes" if total == p.get("authority", 0) + p.get("value", 0) + p.get("policy", 0) + clean_or_other else "no",
            ]
        )
    lines.extend(markdown_table(["Benchmark", "Total", "Authority", "Value", "Policy", "Clean/Other", "Split OK"], primary_rows))

    lines.extend(["", "## Four-Tuple Label Counts", ""])
    tuple_rows = []
    for benchmark in benchmarks:
        labels = label_yes.get(benchmark, {})
        tuple_rows.append(
            [
                benchmark,
                labels.get("clean", 0),
                labels.get("value", 0),
                labels.get("authority", 0),
                labels.get("policy", 0),
            ]
        )
    lines.extend(markdown_table(["Benchmark", "clean=yes", "value=yes", "authority=yes", "policy=yes"], tuple_rows))

    lines.extend(["", "## Can Unsafe Rows Be Split Into Value / Authority / Policy?", ""])
    fit_rows = []
    for benchmark in benchmarks:
        total = summary["by_benchmark"][benchmark]
        p = primary.get(benchmark, {})
        unsafe = total - p.get("clean", 0)
        assigned_unsafe = p.get("authority", 0) + p.get("value", 0) + p.get("policy", 0)
        labels = label_yes.get(benchmark, {})
        multi_label_unsafe = labels.get("authority", 0) + labels.get("value", 0) + labels.get("policy", 0)
        status = "yes" if unsafe == assigned_unsafe else "needs_review"
        fit_rows.append([benchmark, unsafe, assigned_unsafe, multi_label_unsafe, status])
    lines.extend(markdown_table(["Benchmark", "Unsafe rows", "Primary V/A/P assigned", "V+A+P label positives", "Fit"], fit_rows))

    lines.extend(["", "## Review Status", ""])
    review_rows = []
    for benchmark in benchmarks:
        status = review_status.get(benchmark, {})
        review_rows.append(
            [
                benchmark,
                status.get("auto", 0),
                status.get("needs_review", 0),
                status.get("missing", 0),
            ]
        )
    lines.extend(markdown_table(["Benchmark", "Auto", "Needs review", "Missing"], review_rows))

    lines.extend(
        [
            "",
            "Rows marked `needs_review` are still usable as current taxonomy labels, but their value-vs-authority split is heuristic rather than directly supplied by an official per-row taxonomy field.",
            "",
            "## Review Examples",
            "",
        ]
    )

    examples: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        labels = row["taxonomy_labels"]
        if labels.get("review_status") != "needs_review":
            continue
        key = f"{row['benchmark']} / {row['primary_attack_category']}"
        if len(examples[key]) < 3:
            examples[key].append(compact_label_row(row))
    for key in sorted(examples):
        lines.extend([f"### {key}", ""])
        for item in examples[key]:
            labels = item["labels"]
            lines.extend(
                [
                    f"- `{item['case_id']}`",
                    f"  - tuple: `{{clean={labels['clean']}, value={labels['value']}, authority={labels['authority']}, policy={labels['policy']}}}`",
                    f"  - rationale: {labels['rationale']}",
                    f"  - review: {'; '.join(item['review_reasons'])}",
                    f"  - preview: {item['text_preview'][:240].replace(chr(10), ' ')}",
                    "",
                ]
            )

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()

    rows = load_jsonl(args.manifest)
    summary = validate(rows)
    if not summary["valid"]:
        raise SystemExit(json.dumps(summary["errors"], indent=2, ensure_ascii=False))

    args.out_dir.mkdir(parents=True, exist_ok=True)
    labels_path = args.out_dir / "benchmark_taxonomy_labels.jsonl"
    review_path = args.out_dir / "benchmark_taxonomy_review_samples.jsonl"
    report_path = args.out_dir / "benchmark_taxonomy_audit.md"
    summary_path = args.out_dir / "benchmark_taxonomy_audit_summary.json"

    with labels_path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(compact_label_row(row), ensure_ascii=False, sort_keys=True) + "\n")

    with review_path.open("w", encoding="utf-8") as f:
        for row in rows:
            if row["taxonomy_labels"].get("review_status") == "needs_review":
                f.write(json.dumps(compact_label_row(row), ensure_ascii=False, sort_keys=True) + "\n")

    report_path.write_text(render_report(rows, summary), encoding="utf-8")
    audit_summary = {
        "valid": True,
        "manifest": str(args.manifest.relative_to(ROOT)),
        "report": str(report_path.relative_to(ROOT)),
        "labels": str(labels_path.relative_to(ROOT)),
        "review_samples": str(review_path.relative_to(ROOT)),
        **summary,
    }
    summary_path.write_text(json.dumps(audit_summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(audit_summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
